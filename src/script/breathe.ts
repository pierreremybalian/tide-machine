export const WEEK_HOURS = (WEEK_MM.length - 1) * (STEP_MINUTES / 60);

/** Hours into the week: a slow drift through the transition, then the whole week at an even pace, then a slow end. */
export const weekHours = track(
  [
    [0, 0],
    [0.12, 3],
    [0.92, WEEK_HOURS - 3],
    [1, WEEK_HOURS],
  ],
  linear,
);

/** Observed level (m above MLLW) at a time, linear between the six-minute samples, held at the ends. */
export function observedAt(ms: number): number {
  const f = Math.min(Math.max((ms - WEEK_START) / (STEP_MINUTES * 60000), 0), WEEK_MM.length - 1);
  const i = Math.min(Math.floor(f), WEEK_MM.length - 2);
  const t = f - i;
  return (WEEK_MM[i]! * (1 - t) + WEEK_MM[i + 1]! * t) / 1000;
}

/** Lowest and highest observed levels of the week (m above MLLW). */
export const WEEK_RANGE = { min: Math.min(...WEEK_MM) / 1000, max: Math.max(...WEEK_MM) / 1000 };

export function breatheState(local: number) {
  const hours = weekHours(local);
  const ms = WEEK_START + hours * 3600e3;
  return {
    hours,
    ms,
    /** Observed level at the gauge now (m above MLLW). */
    level: observedAt(ms),
    /** The gauge marker and its label. */
    gauge: ramp(local, 0.16, 0.22),
    /** The moving waterline drawn as a thin glow (over the flats and the whole bay). */
    shore: Math.max(windowed(local, 0.46, 0.8, 0.05, 0.05), 1.3 * ramp(local, 0.86, 0.94)),
    /** The HUD trace card. */
    card: windowed(local, 0.2, 1.01, 0.04, 0.0),
    /** The question at the end. */
    question: ramp(local, 0.86, 0.94),
  };
}

const DAY = new Intl.DateTimeFormat('en-US', { timeZone: 'America/Los_Angeles', weekday: 'short', month: 'short', day: 'numeric' });
const TIME = new Intl.DateTimeFormat('en-US', { timeZone: 'America/Los_Angeles', hour: 'numeric', minute: '2-digit' });

/** "Tue, Jun 3" and "2:30 PM" in Pacific time (PDT in June). */
export function pacific(ms: number): { day: string; time: string } {
  return { day: DAY.format(ms), time: TIME.format(ms) };
}

export const breathe = registerStage('breathe', {
  note: `Water levels are a real week (1–7 June 2025) of NOAA’s Golden Gate gauge, played across this stage; the rest of the bay follows 35 NOAA stations. Relief and water ×${EXAGGERATION}; waves at true scale.`,
  readouts(local) {
    const s = breatheState(local);
    const t = pacific(s.ms);
    const rows: Readout[] = [
      { label: t.day, value: `${t.time} PDT`, tone: 'plain' },
      { label: 'Golden Gate gauge', value: `${s.level < 0 ? '−' : ''}${Math.abs(s.level).toFixed(2)} m`, tone: 'b' },
    ];
    return rows;
  },
});
